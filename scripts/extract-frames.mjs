// Usage: npm run frames -- [input=media/hero.mp4] [--width=1440] [--fps=24] [--quality=72]
// Turns the hero clip into a WebP frame sequence that the hero scrubs through on scroll.
import { execFileSync, spawnSync } from 'node:child_process'
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import ffmpeg from 'ffmpeg-static'

const args = process.argv.slice(2)
const flag = (name, fallback) => {
  const hit = args.find((a) => a.startsWith(`--${name}=`))
  return hit ? hit.split('=')[1] : fallback
}
const input = args.find((a) => !a.startsWith('--')) ?? 'media/hero.mp4'
const width = Number(flag('width', 1440))
const fps = flag('fps', null)
const quality = Number(flag('quality', 72))

const outDir = 'public/frames'
rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const filters = [fps && `fps=${fps}`, `scale=${width}:-2:flags=lanczos`].filter(Boolean).join(',')
execFileSync(
  ffmpeg,
  ['-hide_banner', '-loglevel', 'error', '-i', input, '-vf', filters, '-c:v', 'libwebp', '-quality', String(quality), '-compression_level', '6', join(outDir, '%03d.webp')],
  { stdio: 'inherit' },
)

const count = readdirSync(outDir).filter((f) => f.endsWith('.webp')).length
// ffmpeg with no output file exits non-zero but still prints stream info to stderr.
const probe = spawnSync(ffmpeg, ['-hide_banner', '-i', join(outDir, '001.webp')], { encoding: 'utf8' }).stderr.match(/, (\d+)x(\d+)/) ?? []

writeFileSync(
  'src/lib/frames.ts',
  `// Generated by scripts/extract-frames.mjs — do not edit by hand.\nexport const FRAMES = { count: ${count}, width: ${width}, height: ${probe[2] ?? 0}, path: (i: number) => \`/frames/\${String(i + 1).padStart(3, '0')}.webp\` }\n`,
)
console.log(`${count} frames → ${outDir}`)
