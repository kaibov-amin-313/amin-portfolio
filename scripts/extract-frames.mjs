// Usage: npm run frames -- [input=media/hero.mp4] [--fps=24]
// Turns the hero clip into two WebP frame sequences that the hero scrubs through on scroll.
import { execFileSync, spawnSync } from 'node:child_process'
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import ffmpeg from 'ffmpeg-static'

// Landscape for desktops; portrait is a centred 9:16 crop at full height, so phones get the
// face at native resolution instead of a landscape frame upscaled to fill a tall screen.
const SIZES = {
  landscape: { filter: 'scale=1280:-2:flags=lanczos', quality: 62 },
  portrait: { filter: 'crop=ih*9/16:ih,scale=-2:960:flags=lanczos', quality: 60 },
}

const args = process.argv.slice(2)
const flag = (name, fallback) => args.find((a) => a.startsWith(`--${name}=`))?.split('=')[1] ?? fallback
const input = args.find((a) => !a.startsWith('--')) ?? 'media/hero.mp4'
const fps = flag('fps', null)

rmSync('public/frames', { recursive: true, force: true })

const meta = {}
for (const [name, { filter, quality }] of Object.entries(SIZES)) {
  const outDir = join('public/frames', name)
  mkdirSync(outDir, { recursive: true })
  const filters = [fps && `fps=${fps}`, filter].filter(Boolean).join(',')
  execFileSync(
    ffmpeg,
    ['-hide_banner', '-loglevel', 'error', '-i', input, '-vf', filters, '-c:v', 'libwebp', '-quality', String(quality), '-compression_level', '6', join(outDir, '%03d.webp')],
    { stdio: 'inherit' },
  )
  const files = readdirSync(outDir).filter((f) => f.endsWith('.webp'))
  // ffmpeg with no output file exits non-zero but still prints stream info to stderr.
  const [, w, h] = spawnSync(ffmpeg, ['-hide_banner', '-i', join(outDir, files[0])], { encoding: 'utf8' }).stderr.match(/, (\d+)x(\d+)/) ?? []
  const bytes = files.reduce((sum, f) => sum + statSync(join(outDir, f)).size, 0)
  meta[name] = { width: Number(w), height: Number(h), count: files.length }
  console.log(`${name}: ${files.length} frames, ${w}x${h}, ${(bytes / 1024 / 1024).toFixed(2)} MB`)
}

const count = Math.min(...Object.values(meta).map((m) => m.count))
writeFileSync(
  'src/lib/frames.ts',
  `// Generated by scripts/extract-frames.mjs — do not edit by hand.
export type FrameSize = ${Object.keys(SIZES).map((s) => `'${s}'`).join(' | ')}
export const FRAMES = {
  count: ${count},
  sizes: ${JSON.stringify(Object.fromEntries(Object.entries(meta).map(([k, v]) => [k, { width: v.width, height: v.height }])))},
  path: (size: FrameSize, i: number) => \`/frames/\${size}/\${String(i + 1).padStart(3, '0')}.webp\`,
}
`,
)
