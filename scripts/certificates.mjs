// Usage: npm run certificates   (first time: npm run scan:setup)
// Takes originals from media/certificates/ named after an award id (see AWARDS in src/content.ts):
//   techvision-2026.jpg       photo of a certificate → straightened, cleaned "scan" + A4 PDF
//   techvision-2026-2.heic    second page/photo for the same award
//   techvision-2026.pdf       an existing PDF, copied as is
//   techvision-2026-photo.jpg a picture to show as-is (e.g. the award ceremony), no scanning
// If a page outline is detected wrongly, set its corners (in the photo's pixels, any order) in
// media/certificates/corners.json: { "techvision-2026.jpg": [[x,y],[x,y],[x,y],[x,y]] }.
// Results go to public/certificates/ and src/lib/awardDocs.ts.
import { execFileSync, spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { extname, join, parse } from 'node:path'
import ffmpeg from 'ffmpeg-static'

const SRC = 'media/certificates'
const OUT = 'public/certificates'
const PYTHON = '.venv-scan/bin/python'
const PHOTO = new Set(['.jpg', '.jpeg', '.png', '.webp', '.heic'])

const ids = [...readFileSync('src/content.ts', 'utf8').matchAll(/^\s+id: '([^']+)',$/gm)].map((m) => m[1])
const cornersFile = join(SRC, 'corners.json')
const corners = existsSync(cornersFile) ? JSON.parse(readFileSync(cornersFile, 'utf8')) : {}
mkdirSync(SRC, { recursive: true })
rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })
const tmp = mkdtempSync(join(tmpdir(), 'certificates-'))

const byName = (a, b) => parse(a).name.localeCompare(parse(b).name, 'en', { numeric: true })
const files = readdirSync(SRC).filter((f) => !f.startsWith('.') && f !== 'corners.json').sort(byName)
const needsScanner = files.some((f) => PHOTO.has(extname(f).toLowerCase()) && !parse(f).name.endsWith('-photo'))
if (needsScanner && !existsSync(PYTHON)) {
  console.error('The photo scanner needs its Python environment. Run once:  npm run scan:setup')
  process.exit(1)
}

const docs = {}
for (const file of files) {
  const ext = extname(file).toLowerCase()
  const { name } = parse(file)
  const id = ids.find((i) => name === i || name.startsWith(`${i}-`))
  if (!id) {
    console.warn(`skip ${file}: name must start with an award id (${ids.join(', ')})`)
    continue
  }
  let input = join(SRC, file)

  if (ext === '.pdf') {
    copyFileSync(input, join(OUT, `${name}.pdf`))
    ;(docs[id] ??= []).push({ src: `/certificates/${name}.pdf`, kind: 'pdf' })
    continue
  }
  if (!PHOTO.has(ext)) {
    console.warn(`skip ${file}: use PDF, JPG, PNG, WebP or HEIC`)
    continue
  }
  if (ext === '.heic') {
    const jpg = join(tmp, `${name}.jpg`)
    execFileSync('sips', ['-s', 'format', 'jpeg', input, '--out', jpg], { stdio: 'ignore' })
    input = jpg
  }

  if (name.endsWith('-photo')) {
    const out = join(OUT, `${name}.webp`)
    execFileSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-i', input, '-vf', "scale='min(1800,iw)':'min(1800,ih)':force_original_aspect_ratio=decrease", '-c:v', 'libwebp', '-quality', '82', out])
    const [, w, h] = spawnSync(ffmpeg, ['-hide_banner', '-i', out], { encoding: 'utf8' }).stderr.match(/, (\d+)x(\d+)/) ?? []
    ;(docs[id] ??= []).push({ src: `/certificates/${name}.webp`, kind: 'image', width: Number(w), height: Number(h) })
    continue
  }

  const args = ['-I', 'scripts/scan.py', input, join(OUT, name)]
  if (corners[file]) args.push(`--corners=${JSON.stringify(corners[file])}`)
  const result = JSON.parse(execFileSync(PYTHON, args, { encoding: 'utf8' }).trim().split('\n').pop())
  if (!result.found_page && !corners[file]) console.warn(`${file}: no page outline found — cleaned without straightening (set corners in corners.json)`)
  ;(docs[id] ??= []).push({ src: `/certificates/${name}.webp`, pdf: `/certificates/${name}.pdf`, kind: 'scan', width: result.width, height: result.height })
  console.log(`scanned ${file}`)
}
rmSync(tmp, { recursive: true, force: true })

writeFileSync(
  'src/lib/awardDocs.ts',
  `// Generated by scripts/certificates.mjs — do not edit by hand.
export type AwardDoc =
  | { src: string; kind: 'pdf' }
  | { src: string; kind: 'image'; width: number; height: number }
  | { src: string; pdf: string; kind: 'scan'; width: number; height: number }
export const AWARD_DOCS: Record<string, AwardDoc[]> = ${JSON.stringify(docs, null, 2)}
`,
)
console.log(`${Object.values(docs).flat().length} document(s) for ${Object.keys(docs).length} award(s) → ${OUT}`)
if (!existsSync(join(SRC, '.gitkeep'))) writeFileSync(join(SRC, '.gitkeep'), '')
