// Usage: npm run certificates
// Takes originals from media/certificates/ named after an award id (see AWARDS in src/content.ts):
//   techvision-2026.pdf, techvision-2026.jpg, techvision-2026-2.jpg, …
// Photos are re-encoded to WebP (max 1800px) into public/certificates/, PDFs are copied as is,
// and src/lib/awardDocs.ts is regenerated so each award row gets a "View" button.
import { execFileSync, spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { extname, join, parse } from 'node:path'
import ffmpeg from 'ffmpeg-static'

const SRC = 'media/certificates'
const OUT = 'public/certificates'
const IMAGE = new Set(['.jpg', '.jpeg', '.png', '.webp'])

const ids = [...readFileSync('src/content.ts', 'utf8').matchAll(/^\s+id: '([^']+)',$/gm)].map((m) => m[1])
mkdirSync(SRC, { recursive: true })
rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })

const docs = {}
const byName = (a, b) => parse(a).name.localeCompare(parse(b).name, 'en', { numeric: true })
for (const file of readdirSync(SRC).sort(byName)) {
  const ext = extname(file).toLowerCase()
  const { name } = parse(file)
  const id = ids.find((i) => name === i || name.startsWith(`${i}-`))
  if (!id) {
    if (!file.startsWith('.')) console.warn(`skip ${file}: name must start with an award id (${ids.join(', ')})`)
    continue
  }
  if (ext === '.pdf') {
    copyFileSync(join(SRC, file), join(OUT, `${name}.pdf`))
    ;(docs[id] ??= []).push({ src: `/certificates/${name}.pdf`, kind: 'pdf' })
  } else if (IMAGE.has(ext)) {
    const out = join(OUT, `${name}.webp`)
    execFileSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-i', join(SRC, file), '-vf', "scale='min(1800,iw)':'min(1800,ih)':force_original_aspect_ratio=decrease", '-c:v', 'libwebp', '-quality', '80', out])
    const [, w, h] = spawnSync(ffmpeg, ['-hide_banner', '-i', out], { encoding: 'utf8' }).stderr.match(/, (\d+)x(\d+)/) ?? []
    ;(docs[id] ??= []).push({ src: `/certificates/${name}.webp`, kind: 'image', width: Number(w), height: Number(h) })
  } else {
    console.warn(`skip ${file}: use PDF, JPG, PNG or WebP (export HEIC photos as JPG first)`)
  }
}

writeFileSync(
  'src/lib/awardDocs.ts',
  `// Generated by scripts/certificates.mjs — do not edit by hand.
export type AwardDoc = { src: string; kind: 'pdf' } | { src: string; kind: 'image'; width: number; height: number }
export const AWARD_DOCS: Record<string, AwardDoc[]> = ${JSON.stringify(docs, null, 2)}
`,
)
const total = Object.values(docs).flat().length
console.log(`${total} document(s) for ${Object.keys(docs).length} award(s) → ${OUT}`)
if (!existsSync(join(SRC, '.gitkeep'))) writeFileSync(join(SRC, '.gitkeep'), '')
